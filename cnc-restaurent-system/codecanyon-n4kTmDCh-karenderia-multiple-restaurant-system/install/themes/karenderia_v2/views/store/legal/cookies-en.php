<h2>1. What are cookies?</h2>
<p>Cookies are small text files stored on your device when you visit our website. They help the site function correctly and improve your experience.</p>
<p>Two types exist:</p>
<ul>
<li><strong>Session cookies:</strong> temporary cookies deleted when you close your browser.</li>
<li><strong>Persistent cookies:</strong> cookies stored on your device for a set period.</li>
</ul>

